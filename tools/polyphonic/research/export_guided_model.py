"""Export train_purifier.py's evidence trees into the guided detector namespace.

The fitted numbers are copied verbatim; the original DSP-only model is shared.
"""
import argparse
from pathlib import Path
import re


def guided_header(standard_header):
    section = re.search(r'(// Evidence:.*?)(?=// Dsp:|} // namespace purifier)',
                        standard_header, re.DOTALL)
    if not section or not re.search(r'kEvidenceNumFeatures\s*=\s*21\s*;', section[1]):
        raise ValueError('expected a trained 21-feature Evidence tree section')
    return '''// Generated by research/train_purifier.py from neural-guided candidates.
// Experimental 480-mixture model; see docs/testing/polyphonic-detector-research.md.
#pragma once
#include "PolyPurifierModel.h"

namespace polyphonic { namespace detail { namespace guidedPurifier {
using purifier::TreeNode;

''' + section[1].rstrip() + '\n\n} } } // namespace polyphonic::detail::guidedPurifier\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--out', required=True, type=Path)
    args = parser.parse_args()
    args.out.write_text(guided_header(args.source.read_text()))


if __name__ == '__main__':
    main()
